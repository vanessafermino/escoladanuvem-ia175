# 1. Lê o primeiro valor inteiro informado pelo usuário e armazena em A.
# A função int() converte o texto digitado para um número inteiro.
A = int(input("Digite o primeiro valor: "))

# 2. Lê o segundo valor inteiro e armazena em B.
B = int(input("Digite o segundo valor: "))

# 3. Efetua a soma de A e B e atribui o resultado à variável X.
X = A + B

# 4. Imprime o resultado no formato especificado: "X = [valor]"
print(f"X = {X}")